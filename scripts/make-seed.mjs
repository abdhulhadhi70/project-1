// Writes supabase/seed.sql from data/catalogue.ts, so the database starts
// with exactly the demo the site shows today.
//
//   node scripts/make-seed.mjs
import { build } from "esbuild";
import { writeFile, mkdtemp } from "node:fs/promises";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const dir = await mkdtemp(join(tmpdir(), "seed-"));
const out = join(dir, "catalogue.mjs");
await build({
  entryPoints: [join(root, "data/catalogue.ts")],
  bundle: true, format: "esm", platform: "node", outfile: out,
  alias: { "@": root }, logLevel: "error",
});
const { areas, shops, pieces, sampleRates } = await import(pathToFileURL(out).href);

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs, type) => `array[${xs.map(q).join(", ")}]::${type}[]`;
const sql = [];
const w = (s) => sql.push(s);

w(`-- Generated by scripts/make-seed.mjs from data/catalogue.ts. Do not edit by hand.
-- DEMONSTRATION DATA: invented jewellers, sample rates. See README for how
-- to remove it before launch.
begin;
`);
w("insert into public.areas (slug, name, emirate, note, lat, lng, sort_order) values");
w(areas.map((a, i) => `  (${q(a.slug)}, ${q(a.name)}, ${q(a.emirate)}, ${q(a.note)}, ${a.lat}, ${a.lng}, ${i})`).join(",\n") + ";\n");

w("insert into public.gold_rates (purity, rate_per_gram_aed, effective_at) values");
w(Object.entries(sampleRates.perGram).map(([k, v]) => `  (${q(k)}, ${v}, ${q(sampleRates.asOf)})`).join(",\n") + ";\n");

w("insert into public.shops (slug, name, area, address, lat, lng, about, speciality, hours, languages, is_approved, is_active, is_demo, featured_order) values");
w(shops.map((s, i) => `  (${q(s.slug)}, ${q(s.name)}, ${q(s.area)}, ${q(s.address)}, ${s.lat}, ${s.lng}, ${q(s.about)}, ${q(s.speciality)}, ${q(s.hours)}, ${arr(s.languages, "text")}, true, true, true, ${i + 1})`).join(",\n") + ";\n");

// Demo stock counts as confirmed when it is loaded; fixed dates would let
// the 30-day rule hide the whole demo a month later.
w(`insert into public.pieces (shop_id, code, slug, name, category, purity, fineness, weight_grams, making_charge_type,
  making_charge_value, stones, occasions, wearer, style, price_mode, price_aed, description, images, listed_at, stock_confirmed_at)
select s.id, v.* from (values`);
w(pieces.map((p) => {
  const m = p.makingCharge;
  const mValue = m ? (m.type === "percent" ? m.value : m.aed) : null;
  return `  (${q(p.shop)}, ${q(p.code)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.category)}::public.piece_category, ${q(p.purity)}::public.purity, ${q(p.fineness)},
   ${p.weightGrams ?? "null"}::numeric, ${q(m?.type)}::public.making_charge_type, ${mValue ?? "null"}::numeric, ${q(p.stones)},
   ${arr(p.occasions, "public.occasion")}, ${q(p.wearer)}::public.wearer, ${q(p.style)}::public.piece_style,
   ${q(p.price.kind)}::public.price_mode, ${p.price.kind === "listed" ? p.price.aed : "null"}::numeric, ${q(p.description)},
   ${arr(p.images, "text")}, ${q(p.listedAt)}::timestamptz, now())`;
}).join(",\n"));
w(`) as v(shop_slug, code, slug, name, category, purity, fineness, weight_grams, making_charge_type, making_charge_value,
  stones, occasions, wearer, style, price_mode, price_aed, description, images, listed_at, stock_confirmed_at)
join public.shops s on s.slug = v.shop_slug;
`);
w("commit;");
await writeFile(join(root, "supabase/seed.sql"), sql.map((s) => s.replace(/^(.*)$/s, "$1")).join("\n").replace(/select s.id, v\.\*/, "select s.id, v.code, v.slug, v.name, v.category, v.purity, v.fineness, v.weight_grams, v.making_charge_type,\n  v.making_charge_value, v.stones, v.occasions, v.wearer, v.style, v.price_mode, v.price_aed, v.description, v.images, v.listed_at, v.stock_confirmed_at") + "\n");
console.log(`seed.sql: ${areas.length} areas, ${shops.length} shops, ${pieces.length} pieces`);
